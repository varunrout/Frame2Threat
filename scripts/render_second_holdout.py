"""Write ``reports/repro/second_holdout.md`` from ``reports/repro/second_holdout.json``; scores nothing.

Every number comes from the JSON written by ``scripts/second_holdout.py``. The verdicts apply the reading rules fixed
in ``reports/repro/second_holdout_protocol.md``.

Usage:  python scripts/render_second_holdout.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPRO = ROOT / "reports" / "repro"
NAMES = {
    "XGB": "Event-time XGBoost",
    "GRU": "Event-time GRU",
    "LR_xy": "Ball x/y logistic (old baseline)",
    "GBM_pos": "Position-only boosted (new baseline)",
}
TARGETS = {"euro2020": "Euro 2020", "euro2024": "Euro 2024", "test": "In-cohort test"}


def ci(b: dict, nd: int = 3) -> str:
    return f"{b['estimate']:.{nd}f} [{b['ci_low']:.{nd}f}, {b['ci_high']:.{nd}f}]"


def above_zero(b: dict) -> str:
    return "the lift holds" if b["ci_low"] > 0 else "the lift is **not shown**"


def generalises(b: dict, ref: float) -> str:
    return "did **not** generalise" if b["ci_high"] < ref else "generalised"


def render(d: dict) -> str:
    r = d["results"]
    ref = d["reference_auc"]
    prov = d["provenance"]
    gbm = d["baselines"]["GBM_pos"]
    e20 = r["euro2020"]
    L = [
        "# Second sealed holdout (UEFA Euro 2020) and a position-only boosted baseline",
        "",
        "Scored **once** under [second_holdout_protocol.md](second_holdout_protocol.md), committed before any of it",
        "was scored. The committed models, thresholds and features are unchanged. Every number below is read from",
        "[second_holdout.json](second_holdout.json); this page is generated by `scripts/render_second_holdout.py`.",
        "",
        f"Euro 2020: {e20['matches']} matches, {e20['possessions_with_snapshots']:,} possessions, "
        f"{e20['eligible_snapshots']:,} eligible snapshots (danger prevalence {e20['snapshot_prevalence']:.3f}). "
        "No pipeline fix was needed and the run was not repeated.",
        "",
        "The new baseline (`GBM_pos`) was **added after the Euro 2024 scoring** and frozen before it was scored on "
        f"any target. It uses only {', '.join(gbm['features'])} (no event history; `attack_dir` is constant in the "
        "possessing-team frame), was fitted on the original 69 training matches and selected on the 15 validation "
        f"matches only: {gbm['selected_on_validation']}.",
        "",
        "## Verdicts (pre-specified rules)",
        "",
    ]
    for m in ("XGB", "GRU"):
        b = e20["bootstrap_all"][m]["roc_auc"]
        L.append(
            f"- **{NAMES[m]}, Euro 2020:** ROC AUC {ci(b)}; by the rule AUC 0.66 **{generalises(b, ref)}**."
        )
    for t in ("euro2020", "euro2024", "test"):
        for m in ("XGB", "GRU"):
            b = r[t]["bootstrap_all"][f"{m} - GBM_pos"]["roc_auc"]
            L.append(
                f"- **Lift of {m} over the boosted position baseline, {TARGETS[t]}, all snapshots:** {ci(b)}, "
                f"so {above_zero(b)}."
            )
    L += [
        "",
        "## ROC AUC, all eligible snapshots (500 match-level bootstrap resamples, 95% interval)",
        "",
        "| Model | Euro 2020 | Euro 2024 | In-cohort test |",
        "|---|---|---|---|",
    ]
    rows = ["XGB", "GRU", "LR_xy", "GBM_pos"]
    for m in rows:
        L.append(
            f"| {NAMES[m]} | "
            + " | ".join(ci(r[t]["bootstrap_all"][m]["roc_auc"]) for t in TARGETS)
            + " |"
        )
    for k in ("XGB - LR_xy", "GRU - LR_xy", "XGB - GBM_pos", "GRU - GBM_pos", "GRU - XGB"):
        L.append(
            f"| Difference {k.replace(' - ', ' minus ')} | "
            + " | ".join(ci(r[t]["bootstrap_all"][k]["roc_auc"]) for t in TARGETS)
            + " |"
        )
    L += [
        "",
        "## ROC AUC, one snapshot per possession (seed 42)",
        "",
        "| Model | Euro 2020 | Euro 2024 | In-cohort test |",
        "|---|---|---|---|",
    ]
    for m in rows + ["XGB - GBM_pos", "GRU - GBM_pos", "GRU - XGB"]:
        name = NAMES.get(m, "Difference " + m.replace(" - ", " minus "))
        L.append(
            f"| {name} | "
            + " | ".join(ci(r[t]["bootstrap_one_per_possession"][m]["roc_auc"]) for t in TARGETS)
            + " |"
        )
    L += [
        "",
        "## Calibration (all eligible snapshots)",
        "",
        f"ECE: {d['definitions']['ece']}.",
        "",
        "| Model | ECE Euro 2020 | ECE Euro 2024 | ECE test | Brier Euro 2020 | Brier Euro 2024 | Brier test |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in rows:
        L.append(
            f"| {NAMES[m]} | "
            + " | ".join(f"{r[t]['ece'][m]:.3f}" for t in TARGETS)
            + " | "
            + " | ".join(f"{r[t]['all_snapshots'][m]['brier']:.3f}" for t in TARGETS)
            + " |"
        )
    op = d["precision_operating_point_rule"]
    thr = d["thresholds"]["precision"]
    L += [
        "",
        "## Operating points (Euro 2020 and in-cohort test)",
        "",
        f"False-alert rate: {d['definitions']['false_alert_rate']}. Precision operating point: {op['rule']} "
        f"(target precision {op['target_precision']}).",
        "",
    ]
    for m in ("XGB", "GRU"):
        t = thr[m]
        if t["reachable"]:
            L.append(
                f"- {NAMES[m]}: precision threshold {t['threshold']:.3f}, chosen on validation (validation "
                f"precision {t['precision']:.3f}, recall {t['recall']:.3f}, {t['alert_share']:.1%} of validation "
                "snapshots alerted)."
            )
        else:
            L.append(
                f"- {NAMES[m]}: **no threshold reaches precision {op['target_precision']} on validation** with at "
                f"least {op['min_validation_alert_share']:.0%} of snapshots alerted, so this operating point is not "
                "reachable, as the protocol requires it to be reported."
            )
    L += [
        "",
        "| Operating point | Model | Target | Threshold | Precision | Recall | False-alert rate | Dangerous "
        "possessions alerted | Median lead (events) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for key, label in (
        ("alerts_validation_prevalence", "Validation prevalence"),
        ("alerts_precision_operating_point", "Precision-oriented"),
    ):
        for m in ("XGB", "GRU"):
            for t in ("euro2020", "test"):
                a = r[t][key][m]
                if a is None:
                    L.append(f"| {label} | {m} | {TARGETS[t]} | not reachable | | | | | |")
                    continue
                L.append(
                    f"| {label} | {m} | {TARGETS[t]} | {a['threshold']:.3f} | {a['precision']:.3f} | "
                    f"{a['recall']:.3f} | {a['false_alert_rate']:.1%} of {a['safe_possessions']:,} | "
                    f"{a['dangerous_alert_rate']:.1%} of {a['dangerous_possessions']:,} | "
                    f"{a['median_lead_events']:.0f} |"
                )
    chk = d["reproduces_earlier_model_results"]
    same = all(v["identical"] for t in chk.values() for v in t.values())
    L += [
        "",
        "## What this shows and what it does not",
        "",
        "- In every target the lift of the event-time models over the nonlinear position-only baseline is smaller "
        "than their lift over the linear ball x/y baseline (compare the difference rows). Part of the earlier lift "
        "came from the linear baseline's inability to model the goal's geometry, not from the event history.",
        "- On the 15 in-cohort test matches that smaller lift is not distinguishable from zero on all snapshots; "
        "it is on the two larger external holdouts and on one snapshot per possession.",
        "- On Euro 2020 the GRU ranks slightly below XGBoost (difference row above); on Euro 2024 and the test "
        "split they are indistinguishable.",
        "- Calibration: on Euro 2020 both baselines have a lower ECE than both models (table above). The scores are a "
        "ranking aid, not calibrated probabilities.",
        "- Two men's international tournaments are two external tests. Training used 64 World Cup 2022 and 35 "
        "Barcelona La Liga 2020/21 matches, so these are close in kind to part of the training data. Club leagues, "
        "other seasons and women's football are untested.",
        f"- The models' earlier results reproduce exactly on the test split and Euro 2024: {same} "
        "(`reproduces_earlier_model_results` in the JSON). Euro 2024 numbers for the models are unchanged; only the "
        "new baseline and its differences are new there.",
        "",
        "## Provenance",
        "",
        f"- Command: `{prov['command']}`, run once on {prov['timestamp_utc']} (refuses to overwrite its result or "
        "run on a dirty tree)",
        f"- Git SHA `{prov['git_sha']}`, working tree dirty: {prov['git_dirty']}",
        f"- Data: StatsBomb Open Data revision `{prov['open_data_revision']}`; Euro 2020 events SHA-256 "
        f"`{d['data']['euro2020']['events_parsed_sha256']}`",
        f"- Config `{prov['config']}`, SHA-256 `{prov['config_sha256']}`; seed {prov['seed']}, {prov['n_boot']} "
        "bootstrap resamples",
        "- Model SHA-256: "
        + ", ".join(f"`{k}` `{v[:12]}…`" for k, v in prov["files_sha256"].items()),
        "- Packages: "
        + ", ".join(f"{k} {v}" for k, v in prov["packages"].items())
        + f"; Python {prov['python']}",
        "",
        "Data: [StatsBomb Open Data](https://github.com/statsbomb/open-data). Derived figures are published under its "
        "licence and attribution requirements.",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    d = json.loads((REPRO / "second_holdout.json").read_text(encoding="utf-8"))
    (REPRO / "second_holdout.md").write_text(render(d), encoding="utf-8")
    print(f"wrote {REPRO / 'second_holdout.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
