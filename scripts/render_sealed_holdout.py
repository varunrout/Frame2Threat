"""Write ``reports/repro/sealed_holdout.md`` from the two result files; scores nothing.

Every number comes from ``reports/repro/sealed_holdout.json`` (Euro 2024, scored once) and
``reports/repro/frozen_metrics_test.json`` (original test split, same code and definitions), both written by
``scripts/sealed_holdout.py``. The verdict applies the rule fixed in ``sealed_holdout_protocol.md``.

Usage:  python scripts/render_sealed_holdout.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPRO = ROOT / "reports" / "repro"
NAMES = {
    "XGB": "Event-time XGBoost",
    "GRU": "Event-time GRU",
    "LR_xy": "Ball x/y logistic baseline",
}


def ci(block: dict, nd: int = 3) -> str:
    return f"{block['estimate']:.{nd}f} [{block['ci_low']:.{nd}f}, {block['ci_high']:.{nd}f}]"


def verdict(auc: dict, ref: float) -> str:
    return "did **not** generalise" if auc["ci_high"] < ref else "generalised"


def lift(delta: dict) -> str:
    return "holds" if delta["ci_low"] > 0 else "**not shown**"


def render(hold: dict, test: dict) -> str:
    h, t = hold["results"], test["results"]
    ref = hold["reference_auc"]
    prov = hold["provenance"]
    ba_h, ba_t = h["bootstrap_all"], t["bootstrap_all"]
    bo_h, bo_t = h["bootstrap_one_per_possession"], t["bootstrap_one_per_possession"]
    L = [
        "# Sealed holdout: UEFA Euro 2024",
        "",
        "One external test of the committed event-time models, scored **once** under the protocol fixed",
        "before any holdout input was built: [sealed_holdout_protocol.md](sealed_holdout_protocol.md). No model,",
        "threshold, feature or hyper-parameter was changed. Numbers: [sealed_holdout.json](sealed_holdout.json)",
        "(holdout) and [frozen_metrics_test.json](frozen_metrics_test.json) (original test split, same code and",
        "definitions). This page is generated by `scripts/render_sealed_holdout.py`.",
        "",
        f"Holdout: {hold['data']['competition']}, {h['matches']} matches, {h['possessions_with_snapshots']:,} "
        f"possessions, {h['eligible_snapshots']:,} eligible snapshots (danger prevalence "
        f"{h['snapshot_prevalence']:.3f}). In-cohort test: {t['matches']} matches, "
        f"{t['possessions_with_snapshots']:,} possessions, {t['eligible_snapshots']:,} snapshots (prevalence "
        f"{t['snapshot_prevalence']:.3f}). No pipeline fix was needed; the holdout was scored in a single run.",
        "",
        "## Verdict",
        "",
    ]
    for m in ("XGB", "GRU"):
        L.append(
            f"- **{NAMES[m]}:** holdout ROC AUC {ci(ba_h[m]['roc_auc'])}; the reference {ref} lies "
            f"{'inside' if ba_h[m]['roc_auc']['ci_low'] <= ref <= ba_h[m]['roc_auc']['ci_high'] else 'outside'} "
            f"the interval, so by the pre-specified rule AUC 0.66 **{verdict(ba_h[m]['roc_auc'], ref)}** to "
            f"Euro 2024. Lift over ball x/y: {ci(ba_h[m + ' - LR_xy']['roc_auc'])}, which "
            f"{lift(ba_h[m + ' - LR_xy']['roc_auc'])}."
        )
    L += [
        "",
        "## ROC AUC (500 match-level bootstrap resamples, 95% interval)",
        "",
        "| Model | Euro 2024, all snapshots | In-cohort test, all snapshots | Euro 2024, one per possession "
        "| In-cohort test, one per possession |",
        "|---|---|---|---|---|",
    ]
    for m in ("XGB", "GRU", "LR_xy"):
        L.append(
            f"| {NAMES[m]} | {ci(ba_h[m]['roc_auc'])} | {ci(ba_t[m]['roc_auc'])} | "
            f"{ci(bo_h[m]['roc_auc'])} | {ci(bo_t[m]['roc_auc'])} |"
        )
    for a, b in (("XGB", "LR_xy"), ("GRU", "LR_xy"), ("GRU", "XGB")):
        k = f"{a} - {b}"
        L.append(
            f"| Difference {a} minus {b} | {ci(ba_h[k]['roc_auc'])} | {ci(ba_t[k]['roc_auc'])} | "
            f"{ci(bo_h[k]['roc_auc'])} | {ci(bo_t[k]['roc_auc'])} |"
        )
    L += [
        "",
        f"The ball x/y baseline is refit on the original training matches only ({hold['baseline_train_snapshots']:,}"
        " snapshots) and never sees a holdout match.",
        "",
        "## Alerts and calibration at the validation-chosen thresholds",
        "",
        f"False-alert rate: {hold['definitions']['false_alert_rate']}.  ",
        f"ECE: {hold['definitions']['ece']}.",
        "",
        "| | XGBoost, Euro 2024 | XGBoost, in-cohort test | GRU, Euro 2024 | GRU, in-cohort test |",
        "|---|---|---|---|---|",
    ]

    def row(label: str, fn) -> str:
        return f"| {label} | {fn(h, 'XGB')} | {fn(t, 'XGB')} | {fn(h, 'GRU')} | {fn(t, 'GRU')} |"

    L += [
        row("Threshold", lambda r, m: f"{r['alerts'][m]['threshold']:.3f}"),
        row("Precision (snapshots)", lambda r, m: f"{r['alerts'][m]['precision']:.3f}"),
        row("Recall (snapshots)", lambda r, m: f"{r['alerts'][m]['recall']:.3f}"),
        row(
            "False-alert rate (safe possessions alerted)",
            lambda r, m: f"{r['alerts'][m]['false_alert_rate']:.1%} of "
            f"{r['alerts'][m]['safe_possessions']:,}",
        ),
        row(
            "Dangerous possessions alerted before the outcome",
            lambda r, m: f"{r['alerts'][m]['dangerous_alert_rate']:.1%} of "
            f"{r['alerts'][m]['dangerous_possessions']:,}",
        ),
        row(
            "Median lead time (events)", lambda r, m: f"{r['alerts'][m]['median_lead_events']:.0f}"
        ),
        row("ECE (snapshot-weighted, 10 bins)", lambda r, m: f"{r['ece'][m]:.3f}"),
        row("Brier score", lambda r, m: f"{r['all_snapshots'][m]['brier']:.3f}"),
        "",
        "## What this shows and what it does not",
        "",
        "- It shows that the committed models rank Euro 2024 snapshots about as well as they ranked the 15 "
        "in-cohort test matches, on 51 matches never used for training, validation or threshold choice, and "
        "that the small lift over ball position is still there.",
        "- It does not make the score a good early-warning tool: the AUC is still modest, most of the signal is "
        "still ball position, and an alert still fires on a large share of safe possessions (table above).",
        "- Calibration is worse on the holdout than in-cohort (ECE above). Treat the score as a ranking, "
        "not a probability.",
        "- It is one competition: international tournament football, men, 360-era data. It says nothing yet "
        "about other leagues, seasons, club football outside the training cohort, or women's football. The "
        "training cohort already contained a World Cup, so this is the closest kind of competition, not the "
        "hardest test.",
        "- Snapshots within a possession are correlated; the intervals resample whole matches.",
        f"- The in-cohort column re-scores the committed models with today's arrays builder: "
        f"{t['eligible_snapshots']:,} test snapshots and AUC {t['all_snapshots']['XGB']['roc_auc']:.4f} "
        f"(XGBoost) / {t['all_snapshots']['GRU']['roc_auc']:.4f} (GRU). The documented re-score (0.6649 / "
        "0.6636, [artefact_check.md](artefact_check.md); 43,541 snapshots in "
        "[repair_evaluation.json](repair_evaluation.json)) was computed on an earlier build of the same 99 "
        "matches. The cause of the difference has not been established (see CLAIMS.md open item 4 for a "
        "related known difference). The holdout uses today's builder, so the in-cohort column is the "
        "like-for-like comparison.",
        "",
        "## Provenance",
        "",
        f"- Command: `{prov['command']}` (run once; `scripts/sealed_holdout.py` refuses to overwrite the result)",
        f"- Git SHA: `{prov['git_sha']}`; working tree dirty: {prov['git_dirty']} (pre-existing uncommitted "
        "edits to `scripts/prepare_event_time.py` and `src/app/enhanced_possession_page.py`, neither on the "
        "scoring path)",
        f"- Data: StatsBomb Open Data revision `{prov['open_data_revision']}`; holdout events SHA-256 "
        f"`{hold['data']['events_parsed_sha256']}`",
        f"- Config: `{prov['config']}`, SHA-256 `{prov['config_sha256']}`; seed {prov['seed']}, "
        f"{prov['n_boot']} bootstrap resamples",
        "- Model SHA-256: "
        + ", ".join(f"`{k}` `{v[:12]}…`" for k, v in prov["files_sha256"].items()),
        "- Packages: "
        + ", ".join(f"{k} {v}" for k, v in prov["packages"].items())
        + f"; Python {prov['python']}",
        "",
        "Data: [StatsBomb Open Data](https://github.com/statsbomb/open-data). Derived figures are published "
        "under its licence and attribution requirements.",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    hold = json.loads((REPRO / "sealed_holdout.json").read_text(encoding="utf-8"))
    test = json.loads((REPRO / "frozen_metrics_test.json").read_text(encoding="utf-8"))
    (REPRO / "sealed_holdout.md").write_text(render(hold, test), encoding="utf-8")
    print(f"wrote {REPRO / 'sealed_holdout.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
